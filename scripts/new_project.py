#!/usr/bin/env python3
"""new_project.py -- scaffold an mv-studio (lyric-MV) project from the skill's template (base: vocaloid-style-mv).

  python scripts/new_project.py <target_dir> [--song song.wav] [--lyrics lyrics.lrc] [--title NAME] [--title-sub LATIN]
                                [--artist NAME] [--credit "Music / Lyrics / Movie：Artist"] [--style vocaloid|interface|magazine]
                                [--art codex|grok|novelai] [--mode solo|team] [--no-git]
                                [--setup] [--setup-args "..."]
                                [--force]
  python scripts/new_project.py <project> --upgrade [--apply]

What it does
  * copies template/ to <target_dir>, leaving out everything that setup fetches or a tool generates
    (node_modules/, vendor/, render/, the JIZURA bundle, analysis outputs, songs, caches); font files are copied
    when the template already has them (saves the ~260 MB download)
  * PROJECT_README.md becomes the project's README.md; this kit's check_env.py is copied to tools/
  * --song   -> audio/song.wav (WAV is copied as is; mp3 / flac / m4a / ogg ... are converted with ffmpeg)
  * --lyrics -> analysis/lyrics_mv.lrc when the file has LRC time tags, else analysis/lyrics_official.txt
                (plain official text: timings come later, see references/03-audio-and-lyrics.md)
  * --title / --title-sub / --artist / --credit set Z.TITLE / Z.TITLE_SUB / Z.ARTIST / Z.CREDIT in engine/timeline.js
                (HUD, end card, 9:16 header and footer). --title alone empties Z.TITLE_SUB;
                --credit alone also sets Z.ARTIST to the name after its first role (： or :), up to the next ' / '
  * --style  own (default: the film designs its own style; engine/timeline.js is the blank starter) | a preset the user
                asked for: vocaloid | interface | magazine (engine/timeline.js is a copy of engine/starters/<starter>.js)
  * --mode   solo (default) | team -> project.json; --no-git skips `git init` (the default when git exists)
  * --art    the image generator the user chose -> art.config.json "provider" (tools/artgen.py; default: ask later)
  * --setup  runs setup.ps1 (Windows) or setup.sh (macOS / Linux) inside the new project
  * writes .mv-studio.json: the skill commit and a hash of every framework file it copied
Then it prints the next steps.

--upgrade brings an existing project's framework files (engine/core, tools/, ...) up to this skill's template: a file
the project never changed is updated, a new one is added; a file changed in the project is kept and listed (merge it
by hand from template/), and one the template dropped is listed, never deleted. engine/timeline.js, project.json,
art.config.json and assets/style/palettes.json are the film's and are never touched. It lists the plan; --apply
does it. A project made before .mv-studio.json has no record: every file that differs is listed, none is changed. Stdlib only. Author: NikusonP -- vocaloid-style-mv-pipeline, MIT licence.
"""
from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
import os
import re
import shlex
import shutil
import stat
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE.parent / "template"
IS_WIN = os.name == "nt"

# relative (posix) paths inside the template that are never copied: fetched / built at setup or generated by tools
SKIP_DIRS = {"node_modules", "vendor", "__pycache__", ".venv", "venv", ".pytest_cache", "render", "_probe",
             ".cache", "blender/renders", "analysis/stems", "analysis/asr"}
SKIP_DIR_GLOBS = ["jizura/probe*"]
SKIP_FILES = {"jizura/app/jizura_engine.js", "jizura/parts.json", "docs/AUDIO_MAP.md"}
SKIP_FILE_GLOBS = ["audio/*", "analysis/*", "*.pyc", "*.raw.png", "*.mp4", "*.mov", "*.mkv", "*.blend1",
                   "Thumbs.db", ".DS_Store", "desktop.ini", "npm-debug.log*"]
KEEP_FILES = {"audio/.gitkeep", "analysis/.gitkeep"}
MAKE_DIRS = ["audio", "analysis", "assets/char", "assets/bg", "docs", "engine/tests"]
# --style -> starter in engine/starters (where each style's code lives: references/05-engine.md §12)
STYLES = {"own": "blank", "vocaloid": "vocaloid", "interface": "interface", "magazine": "magazine"}
STYLE_ALIASES = {"tegaki": "vocaloid", "vocaloid:tegaki": "vocaloid", "signal": "vocaloid", "vocaloid:signal": "vocaloid",
                 "interface:screen": "interface", "screen": "interface", "treatise": "interface", "interface:treatise": "interface", "none": "own", "blank": "own",
                 "zine": "magazine", "print": "magazine", "riso": "magazine", "雑誌": "magazine"}  # incl. the names before the merge
LRC_TAG = re.compile(r"^\s*\[\d{1,2}:\d{2}(?:[.:]\d{1,3})?\]", re.M)
RECORD = ".mv-studio.json"
INDEX = "index/index.jsonl"   # built from the project's code by tools/build_index.mjs
FILM_FILES = {"engine/timeline.js", "project.json", "art.config.json", "assets/style/palettes.json"}   # the film's own


def ignore_factory(src_root: Path):
    def ignore(dirpath, names):
        rel_dir = Path(dirpath).resolve().relative_to(src_root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        out = set()
        for n in names:
            rel = rel_dir + n
            full = Path(dirpath) / n
            if full.is_dir():
                if n in SKIP_DIRS or rel in SKIP_DIRS or any(fnmatch.fnmatch(rel, g) for g in SKIP_DIR_GLOBS):
                    out.add(n)
            elif rel not in KEEP_FILES and (rel in SKIP_FILES or any(fnmatch.fnmatch(rel, g) or fnmatch.fnmatch(n, g)
                                                                     for g in SKIP_FILE_GLOBS)):
                out.add(n)
        return out
    return ignore


def sig(p: Path) -> str | None:
    """16 hex of the file's SHA-1 (as template/tools/kit_env.py file_sig), None when missing."""
    if not p.is_file():
        return None
    h = hashlib.sha1()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()[:16]


def framework_files() -> dict[str, Path]:
    """{project path: template source} for every file copy_template copies, the film's own files left out."""
    root, ignore, out = TEMPLATE.resolve(), ignore_factory(TEMPLATE.resolve()), {}
    for d, dirs, files in os.walk(root):
        skip = ignore(d, dirs + files)
        dirs[:] = [n for n in dirs if n not in skip]
        for n in files:
            if n not in skip:
                rel = (Path(d) / n).relative_to(root).as_posix()
                out["README.md" if rel == "PROJECT_README.md" else rel] = Path(d) / n
    out["tools/check_env.py"] = HERE / "check_env.py"
    return {k: v for k, v in out.items() if k not in FILM_FILES}


def skill_commit() -> str | None:
    r = subprocess.run(["git", "-C", str(HERE.parent), "rev-parse", "--short", "HEAD"], capture_output=True, text=True) \
        if shutil.which("git") else None
    return r.stdout.strip() if r and r.returncode == 0 else None


def write_record(dst: Path, files: dict[str, str | None]):
    (dst / RECORD).write_text(json.dumps({"version": 1, "skill_commit": skill_commit(), "files": dict(sorted(files.items()))},
                                         indent=1) + "\n", encoding="utf-8")


def make_exec(p: Path):
    if not IS_WIN and p.is_file():
        p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def upgrade(dst: Path, apply: bool) -> int:
    if not (dst / "engine" / "core" / "main.js").is_file():
        sys.exit(f"{dst} is not an mv-studio project (no engine/core/main.js)")
    rp = dst / RECORD
    rec = json.loads(rp.read_text(encoding="utf-8")).get("files") if rp.is_file() else None
    plan = {"update": [], "add": [], "keep (changed in the project)": [], "keep (deleted in the project)": [],
            "differs (no record: compare by hand)": []}
    new_rec = dict(rec or {})
    src = framework_files()
    for rel, s in sorted(src.items()):
        if rel == INDEX:
            continue                                               # generated: rebuilt below, never "changed in the project"
        up, cur = sig(s), sig(dst / rel)
        if cur == up:
            new_rec[rel] = up
        elif rec is None:
            plan["add" if cur is None else "differs (no record: compare by hand)"].append(rel)
            if cur is None:
                new_rec[rel] = up
        elif cur is None:
            plan["add" if rel not in rec else "keep (deleted in the project)"].append(rel)
            if rel not in rec:
                new_rec[rel] = up
        elif rec.get(rel) == cur:
            plan["update"].append(rel)
            new_rec[rel] = up
        else:
            plan["keep (changed in the project)"].append(rel)     # its record stays the old hash: still "changed" next time
    gone = sorted(set(rec or {}) - set(src))
    print(f"template : {TEMPLATE.resolve()} ({skill_commit() or 'no git'})\nproject  : {dst}"
          + ("" if rec is not None else f"\n  no {RECORD} (made before it): only missing files are added"))
    for k, v in [*plan.items(), ("dropped by the template (left in place)", gone)]:
        if v:
            print(f"  {k}: {len(v)}\n    " + "\n    ".join(v[:40]) + (f"\n    ... {len(v) - 40} more" if len(v) > 40 else ""))
    if not apply:
        print("\nnothing changed: re-run with --apply to do it" if plan["update"] or plan["add"] else "\nup to date")
        return 0
    for rel in plan["update"] + plan["add"]:
        (dst / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src[rel], dst / rel)
        if rel.startswith(("tools/", "demo/")) or rel == "setup.sh":
            make_exec(dst / rel)
    shutil.copy2(src[INDEX], dst / INDEX)                          # the skill's manual rows, then the project's own code
    r = subprocess.run(["node", "tools/build_index.mjs"], cwd=dst, capture_output=True, text=True)
    print(r.stdout.strip() or f"index not rebuilt ({r.stderr.strip()[:200]}): run node tools/build_index.mjs")
    write_record(dst, {k: v for k, v in new_rec.items() if k not in gone})
    print(f"\nupdated {len(plan['update'])}, added {len(plan['add'])} -> {RECORD}. Then: node tools/verify.mjs --quick")
    return 0


def copy_template(dst: Path, force: bool):
    if not (TEMPLATE / "engine" / "core" / "main.js").is_file():
        sys.exit(f"template not found at {TEMPLATE} (run this script from the skill's scripts/ folder)")
    shutil.copytree(TEMPLATE, dst, ignore=ignore_factory(TEMPLATE.resolve()), dirs_exist_ok=force)
    for d in MAKE_DIRS:
        (dst / d).mkdir(parents=True, exist_ok=True)
    readme = dst / "PROJECT_README.md"
    if readme.is_file():
        readme.replace(dst / "README.md")
    shutil.copy2(HERE / "check_env.py", dst / "tools" / "check_env.py")
    for p in [dst / "setup.sh", *dst.glob("tools/*.py"), *dst.glob("tools/*.mjs"), *dst.glob("demo/*.py")]:
        make_exec(p)
    write_record(dst, {rel: sig(s) for rel, s in framework_files().items()})   # what --upgrade may replace later


def import_song(src: Path, dst: Path):
    out = dst / "audio" / "song.wav"
    if src.suffix.lower() == ".wav":
        shutil.copy2(src, out)
        return out, "copied"
    ff = os.environ.get("FFMPEG") or shutil.which("ffmpeg")
    if not ff:
        sys.exit(f"{src.name} is not a WAV and ffmpeg was not found to convert it (install ffmpeg or pass a .wav)")
    r = subprocess.run([ff, "-y", "-hide_banner", "-loglevel", "error", "-i", str(src), "-vn", "-map", "0:a:0",
                        "-c:a", "pcm_s24le", str(out)])
    if r.returncode != 0 or not out.is_file():
        sys.exit(f"ffmpeg could not convert {src}")
    return out, "converted with ffmpeg (24-bit PCM, original sample rate)"


def import_lyrics(src: Path, dst: Path):
    text = src.read_bytes().decode("utf-8-sig", errors="replace")
    if LRC_TAG.search(text):
        out = dst / "analysis" / "lyrics_mv.lrc"
        kind = "LRC with time tags"
    else:
        out = dst / "analysis" / "lyrics_official.txt"
        kind = "plain text (no time tags): timings still needed"
    out.write_text(text.replace("\r\n", "\n"), encoding="utf-8", newline="\n")   # LF on Windows too
    return out, kind


def timeline_values(a) -> dict:
    """--title / --title-sub / --artist / --credit -> {Z key: new string or None (= keep the template's value)}."""
    sub = a.title_sub if a.title_sub is not None else ("" if a.title else None)   # a new title drops the template's sub-title
    artist = a.artist
    if artist is None and a.credit:
        # the name after the FIRST role: 'Music / Lyrics / Movie：Name' -> 'Name';
        # 'Music / Lyrics：Name / Movie：Maker' -> 'Name' (not the film's maker)
        parts = re.split(r"[：:]", a.credit, maxsplit=1)
        artist = re.split(r"\s+/\s+", parts[1])[0].strip() if len(parts) > 1 else None
        artist = artist or None
    return {"TITLE": a.title, "TITLE_SUB": sub, "ARTIST": artist, "CREDIT": a.credit}


def set_timeline_strings(dst: Path, values: dict):
    """Rewrite the `Z.<KEY> = '...';` string literals at the top of engine/timeline.js (None = leave as is)."""
    tl = dst / "engine" / "timeline.js"
    if not tl.is_file() or all(v is None for v in values.values()):
        return
    s = tl.read_text(encoding="utf-8")
    js = lambda v: "'" + (v.replace("\\", "\\\\").replace("'", "\\'")  # noqa: E731
                          .replace("\r", "").replace("\n", "\\n")) + "'"
    for key, v in values.items():
        if v is None:
            continue
        # the literal may already hold escapes (\' \\) from an earlier run with --force
        s, n = re.subn(rf"^(\s*Z\.{key}\s*=\s*)'(?:[^'\\\n]|\\.)*'", lambda m: m.group(1) + js(v), s, count=1,
                       flags=re.M)
        print(f"  Z.{key:<10}= {js(v)}" if n else f"  note: Z.{key} not found in engine/timeline.js (set it by hand)")
    tl.write_text(s, encoding="utf-8", newline="\n")   # keep the template's LF line endings on Windows


def run_setup(dst: Path, extra: list[str]) -> int:
    if IS_WIN:
        shell = shutil.which("powershell") or shutil.which("pwsh")
        if not shell:
            print("PowerShell not found: run setup.ps1 yourself")
            return 1
        cmd = [shell, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(dst / "setup.ps1"), *extra]
    else:
        cmd = ["bash", str(dst / "setup.sh"), *extra]
    print("\n$ " + " ".join(shlex.quote(c) for c in cmd), flush=True)
    return subprocess.call(cmd, cwd=str(dst))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", help="new project folder (must not exist, or be empty; see --force); with --upgrade, the project")
    ap.add_argument("--upgrade", action="store_true", help="update the project's unchanged framework files to this template")
    ap.add_argument("--apply", action="store_true", help="with --upgrade: do it (default: list the plan)")
    ap.add_argument("--song", help="the song (WAV preferred; other formats are converted with ffmpeg)")
    ap.add_argument("--lyrics", help="lyrics: .lrc with time tags, or the official plain text")
    ap.add_argument("--title", help="film title for Z.TITLE in engine/timeline.js")
    ap.add_argument("--title-sub", help="small Latin line under the title for Z.TITLE_SUB (default with --title: none)")
    ap.add_argument("--artist", help="artist name for Z.ARTIST (9:16 header; default: the name after --credit's colon)")
    ap.add_argument("--credit", help="credit line for Z.CREDIT, e.g. 'Music / Lyrics / Movie：Artist'")
    ap.add_argument("--style", default="own", choices=[*STYLES, *STYLE_ALIASES],
                    help="own (default: the film designs its own style, a blank starter) or a preset the user asked for (<skill>/styles/<preset>/BRIEF.md)")
    ap.add_argument("--mode", default="solo", choices=["solo", "team"],
                    help="solo: one agent builds the film; team: a lead + parallel builders (references/11-team.md)")
    ap.add_argument("--no-git", action="store_true", help="do not git init the project (default: init, if git exists)")
    ap.add_argument("--art", choices=["codex", "grok", "novelai"],
                    help="image generator the user chose (written to art.config.json; default: ask later)")
    ap.add_argument("--setup", action="store_true", help="run setup.ps1 / setup.sh in the new project")
    ap.add_argument("--setup-args", default="", help='extra setup arguments, e.g. "-Lyrics" (Windows) or "--lyrics"')
    ap.add_argument("--force", action="store_true", help="copy into an existing non-empty folder (template files are overwritten)")
    for _s in (sys.stdout, sys.stderr):  # help texts contain 残光 / ō / ：; never crash on a cp1252 / cp932 console
        try:
            _s.reconfigure(errors="replace", **({} if _s.isatty() else {"encoding": "utf-8"}))  # a pipe (an agent's shell) reads UTF-8
        except Exception:  # noqa: BLE001
            pass
    a = ap.parse_args()
    if a.upgrade:
        return upgrade(Path(a.target).expanduser().resolve(), a.apply)
    a.style = STYLE_ALIASES.get(a.style, a.style)
    starter = STYLES[a.style]

    dst = Path(a.target).expanduser().resolve()
    tpl = TEMPLATE.resolve()
    if dst == tpl or tpl in dst.parents or dst in tpl.parents:
        sys.exit(f"refusing to scaffold into {dst}: it overlaps the template {tpl}")
    if dst.exists() and any(dst.iterdir()) and not a.force:
        sys.exit(f"{dst} exists and is not empty (use --force to copy into it)")
    song = Path(a.song).expanduser().resolve() if a.song else None
    lyrics = Path(a.lyrics).expanduser().resolve() if a.lyrics else None
    for p, what in ((song, "--song"), (lyrics, "--lyrics")):
        if p and not p.is_file():
            sys.exit(f"{what}: {p} not found")

    print(f"template : {tpl}\nproject  : {dst}")
    copy_template(dst, a.force)
    tl, starters = dst / "engine" / "timeline.js", dst / "engine" / "starters"
    shutil.copy2(starters / f"{starter}.js", tl)
    if a.style.startswith("vocaloid"):                 # the preset's palettes (P1-P5) become the film's
        shutil.copy2(dst / "engine" / "styles" / "vocaloid" / "palettes.json", dst / "assets" / "style" / "palettes.json")
    print(f"  style  : {a.style} -> engine/timeline.js is the {starter} starter (an example to rewrite: read "
          + ("<skill>/design-a-style.md" if a.style == "own" else f"<skill>/styles/{a.style.split(':')[0]}/BRIEF.md") + ")")
    pj = dst / "project.json"
    proj = json.loads(pj.read_text(encoding="utf-8")) if pj.is_file() else {}
    proj.update({"mode": a.mode, "style": a.style})
    pj.write_text(json.dumps(proj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"  mode   : {a.mode} (project.json)")
    if a.art:
        cfgp = dst / "art.config.json"
        cfg = json.loads(cfgp.read_text(encoding="utf-8")) if cfgp.is_file() else {}
        cfg["provider"] = a.art
        cfgp.write_text(json.dumps(cfg, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"  art    : {a.art} (art.config.json; change with python tools/artgen.py use <name>)")
    n_files = sum(1 for p in dst.rglob("*") if p.is_file())
    fonts = len(list((dst / "engine" / "fonts").glob("*.ttf")))
    print(f"  copied {n_files} files" + (f" (incl. {fonts} font files)" if fonts else " (fonts: downloaded by setup)"))
    if song:
        out, how = import_song(song, dst)
        print(f"  song   : {song.name} -> {out.relative_to(dst).as_posix()} ({how})")
    if lyrics:
        out, kind = import_lyrics(lyrics, dst)
        print(f"  lyrics : {lyrics.name} -> {out.relative_to(dst).as_posix()} ({kind})")
        if lyrics.parent == dst:   # a lyric file left in the project root fails check_no_lyrics: keep the source in audio/
            (dst / "audio").mkdir(exist_ok=True)
            shutil.move(str(lyrics), str(dst / "audio" / lyrics.name))
            print(f"           moved the source {lyrics.name} -> audio/")
            lyrics = dst / "audio" / lyrics.name
        if out.name == "lyrics_official.txt":
            print("           quick timings: python tools/estimate_lrc.py analysis/lyrics_official.txt --start <first sung line, s>"
                  "  (ESTIMATED: tell the user)\n"
                  "           exact timings: forced alignment, references/03-audio-and-lyrics.md §9")
    values = timeline_values(a)
    set_timeline_strings(dst, values)

    if not a.no_git and shutil.which("git") and not (dst / ".git").exists():
        r = subprocess.run(["git", "init", "-q", str(dst)], capture_output=True, text=True)
        print("  git    : initialised (commit at the end of every phase: git add -A && git commit -m \"phase N\")"
              if r.returncode == 0 else f"  git    : init failed ({r.stderr.strip()[:120]})")
    rc = 0
    if a.setup:
        rc = run_setup(dst, shlex.split(a.setup_args, posix=not IS_WIN) if a.setup_args else [])
        print(f"\nsetup {'finished' if rc == 0 else 'FAILED (exit %d) -- fix the reported problem and re-run it' % rc}")

    py = "python" if IS_WIN else "python3"
    setup_cmd = ("powershell -ExecutionPolicy Bypass -File setup.ps1" if IS_WIN else "./setup.sh")
    steps = [f"cd {shlex.quote(str(dst)) if not IS_WIN else dst}"]
    if not a.setup:
        steps.append(f"{setup_cmd}                    # deps, fonts, JIZURA, environment check")
    if song and not lyrics:
        steps.append("# add the official lyrics with timings as analysis/lyrics_mv.lrc (references/03-audio-and-lyrics.md)")
    if lyrics and not song:
        steps.append("# copy the song to audio/song.wav (a WAV; convert others: ffmpeg -i FILE -vn -c:a pcm_s24le audio/song.wav)")
    demo = not song and not lyrics
    if demo:
        steps += [f"{py} demo/make_demo_song.py          # smoke test without a song (or copy yours to audio/song.wav)",
                  ("copy demo\\lyrics_demo.lrc analysis\\lyrics_mv.lrc" if IS_WIN else
                   "cp demo/lyrics_demo.lrc analysis/lyrics_mv.lrc"),
                  ("copy demo\\sections_demo.json analysis\\sections.json" if IS_WIN else
                   "cp demo/sections_demo.json analysis/sections.json") + "   # optional: curated demo sections"]
    name = "demo" if demo else "first"
    steps += [f"{py} tools/analyze_audio.py              # beats, bars, sections -> analysis/audio.json + overview.png",
              ("node tools/stills.mjs --times 1,3.5,8.4,10,12.5,13.6,18.4,19.5,21.2,23.3 --sheet smoke   "
               "# -> render/stills/smoke.jpg" if demo else
               "node tools/stills.mjs --times 1,4,8,14,17,23 --sheet first   # stills + contact sheet in render/stills/"),
              f"node tools/render_final.mjs --name {name}          # full render + audio -> render/{name}.mp4 (add --codec x264 without an NVIDIA GPU)"]
    if demo:
        steps.append("# 9:16 version + review sheets: README.md section 2")
    if lyrics and not LRC_TAG.search(lyrics.read_bytes().decode("utf-8-sig", errors="replace")):
        steps.insert(-3, "# lyrics have no timings yet: see references/03-audio-and-lyrics.md (alignment) "
                         "before writing analysis/lyrics_mv.lrc")
    print("\nNext steps:\n  " + "\n  ".join(steps))
    print("\nengine/timeline.js is " + f"the {starter} starter"
          + ": replace its shots with your storyboard (README.md, SKILL.md phases 3-7).")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
